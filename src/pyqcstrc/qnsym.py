class Qnsym_Octa:
    def __init__(self):
        M0=qnn.Qnnum(np.array([ 0, 0, 1]),2) #  0
        M1=qnn.Qnnum(np.array([ 1, 0, 2]),2) #  1/2
        M2=qnn.Qnnum(np.array([ 0, 1, 2]),2) #  t=sqrt(2)/2
        M3=qnn.Qnnum(np.array([ 0,-1, 2]),2) # -t
        MT=np.array([
            [M2,M2,M0,M0,M0,M0], #
            [M3,M1,M3,M0,M0,M0], #
            [M0,M0,M0,M0,M0,M0], #
            [M0,M0,M0,M3,M2,M0], #
            [M0,M0,M0,M0,M1,M0], #
            [M0,M0,M0,M0,M0,M1]]) #
        smo8=qnm.Qnmat(MT) # matrix of qnnum (qnmat)
        self.shape = MT.shape  #dimension of a vector a
        self.ndim = MT.ndim
        # generate all symmetry operators generated by MT
        MTM=np.array([  # this may be incorrect
            [M6,M0,M0,M0,M0,M0], # 
            [M0,M6,M0,M0,M0,M0], # 
            [M0,M0,M6,M0,M0,M0], # 
            [M0,M0,M0,M6,M0,M0], #
            [M0,M0,M0,M0,M1,M0], #
            [M0,M0,M0,M0,M0,M1]]) # 
        smom=qnm.Qnmat(MTM)
        # generate all symmetry operators generated by MT
        order=np.int64(12)
        self.smo=np.array(24,dtype=qnm.Qnmat)
        smo[0]=smo1  # this should be the unit matrix
        for i in range(order-1):
            smo[i+1]=smo12@smo[i]
        # add mirror plane
        for i in range(1):
            smo[i+12]=smom@smo[i-12]
        self.order=order*2

